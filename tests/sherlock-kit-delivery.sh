#!/bin/bash

set -euo pipefail

# Hermetic: the provisioning exports (DOTFILES_AUTO_UPDATE=0 and the like,
# docs/bootstrap.md) and other dotfiles knobs never reach the code under
# test from the caller; each case sets what it needs.
unset DOTFILES_AUTO_UPDATE DOTFILES_AUTO_STOW DOTFILES_HOST DOTFILES_DIR _DOTFILES_CHECKED \
    DOTFILES_STOW_WITHOUT_OH_MY_ZSH DOTFILES_COLOR AWESOME_SKILLS_AUTO_UPDATE AWESOME_SKILLS_FORCE \
    AWESOME_SKILLS_BG AWESOME_SKILLS_INSTALLER_URL AWESOME_SKILLS_REFRESH_DAYS _AWESOME_SKILLS_CHECKED \
    CODING_AGENT_KIT_CONFIG CODING_AGENT_KIT_COLOR

# How the sherlock-kit submodule reaches lab-ubuntu, wsl-ubuntu and sherlock
# (docs/sherlock-kit.md). The structure checks always run: the .gitmodules
# entry, the gitlink, every link's exact relative text, the anchored ignore
# file and the host matrix. The fixture then stows a fake submodule with the
# real stow-all.sh into temporary homes. --real checks the initialized
# submodule at the gitlink the index records instead of the fixture (the
# bump Action's guard and acceptance). --ci turns every SKIP into a failure.

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

require_all=0
real=0
for argument in "$@"; do
    case "$argument" in
        --ci) require_all=1 ;;
        --real) real=1 ;;
        --help)
            printf 'Usage: %s [--ci] [--real]\n' "$0"
            printf 'Without --real, a fake submodule is stowed into temporary homes.\n'
            printf '%s\n' '--real checks the initialized submodule at the recorded gitlink; --ci fails instead of skipping.'
            exit 0
            ;;
        *)
            printf 'ERROR: unknown test option: %s\n' "$argument" >&2
            exit 2
            ;;
    esac
done

SUBMODULE=common/sherlock-kit/sherlock-kit
SUBMODULE_URL=https://github.com/FridrichMethod/sherlock-kit.git
HOSTS='lab-ubuntu wsl-ubuntu sherlock'
DATA=src/sherlock_kit/data
# The sherlock-kit contract paths C1-C4 the links point at.
CONTRACT="$DATA/rules/workstation.md $DATA/rules/cluster.md $DATA/skills/sherlock-kit/SKILL.md bin/shk"
MARKER="<!-- Generated by dotfiles codex-instructions-sync. Edit common/codex/.codex/AGENTS.md or the host's sherlock-kit rules, then rerun stow-all.sh. -->"
WARNING='[dotfiles] [warn] sherlock-kit submodule not initialized; Codex instructions left unchanged (git submodule update --init --recursive)'
# The dev checkout is never an install path; split so this file is no match.
DEV_CHECKOUT='data/repos/'sherlock-kit

fail() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

skip() {
    if [[ "$require_all" == 1 ]]; then
        fail "CI requires $1"
    fi
    printf 'SKIP: %s\n' "$1"
}

# A bare "! grep" never fails under set -e; this one does.
refute_grep() {
    if grep -Fq -- "$1" "$2"; then
        fail "unexpected '$1' in $2"
    fi
}

# expect_grep TEXT FILE: FILE contains TEXT; expect_line: as a whole line.
expect_grep() {
    grep -Fq -- "$1" "$2" || fail "expected '$1' in $2"
}
expect_line() {
    grep -Fxq -- "$1" "$2" || fail "expected the line '$1' in $2"
}

# A pre-commit run exports the GIT_DIR and GIT_INDEX_FILE of the commit in
# progress; git in a temporary repository must not see them.
unset_git_env() {
    unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_COMMON_DIR GIT_OBJECT_DIRECTORY \
        GIT_ALTERNATE_OBJECT_DIRECTORIES
}

# in_fixture_env CMD...: CMD against a temporary repository, without the
# caller's git environment or the operator's git config.
in_fixture_env() {
    (
        unset_git_env
        export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
        "$@"
    )
}

fixture_git() {
    in_fixture_env git -c user.name=fixture -c user.email=fixture@example.invalid "$@"
}

# expected_links: every tracked sherlock-kit link as "PATH TEXT", one host
# matrix for the rules, both skill directories and the global shk.
expected_links() {
    local host rules
    for host in $HOSTS; do
        rules=workstation.md
        if [[ "$host" == sherlock ]]; then
            rules=cluster.md
        fi
        printf '%s %s\n' \
            "$host/sherlock-kit/.claude/rules/sherlock-kit.md" "../../../../$SUBMODULE/$DATA/rules/$rules" \
            "$host/sherlock-kit/.claude/skills/sherlock-kit" "../../../../$SUBMODULE/$DATA/skills/sherlock-kit" \
            "$host/sherlock-kit/.agents/skills/sherlock-kit" "../../../../$SUBMODULE/$DATA/skills/sherlock-kit" \
            "$host/sherlock-kit/.local/bin/shk" "../../../../$SUBMODULE/bin/shk"
    done
}
LINKS=$(expected_links)

check_gitmodules() {
    local expected actual
    expected=$(printf '%s\n' \
        "submodule.$SUBMODULE.path $SUBMODULE" \
        "submodule.$SUBMODULE.url $SUBMODULE_URL" \
        "submodule.$SUBMODULE.branch main")
    actual=$(git -C "$REPO_ROOT" config -f .gitmodules --get-regexp '^submodule\.common/sherlock-kit/sherlock-kit\.') ||
        fail ".gitmodules has no $SUBMODULE entry"
    [[ "$actual" == "$expected" ]] ||
        fail ".gitmodules entry for $SUBMODULE is not exactly path, url $SUBMODULE_URL and branch main: $actual"
}

# index_listing: the tracked files of every sherlock-kit package as
# "MODE PATH", with " -> TEXT" for a symlink.
index_listing() {
    local mode sha path text pattern='^[^/]+/sherlock-kit(/|$)'
    git -C "$REPO_ROOT" ls-files -s | while read -r mode sha _ path; do
        [[ "$path" =~ $pattern ]] || continue
        if [[ "$mode" == 120000 ]]; then
            text=$(git -C "$REPO_ROOT" cat-file blob "$sha")
            printf '%s %s -> %s\n' "$mode" "$path" "$text"
        else
            printf '%s %s\n' "$mode" "$path"
        fi
    done | LC_ALL=C sort
}

expected_listing() {
    local path text
    {
        printf '%s\n' '100644 common/sherlock-kit/.stow-local-ignore' "160000 $SUBMODULE"
        while read -r path text; do
            printf '120000 %s -> %s\n' "$path" "$text"
        done <<<"$LINKS"
    } | LC_ALL=C sort
}

# The index holds exactly the gitlink (mode 160000), the ignore file and the
# links (mode 120000, exact relative text): no other host, no absolute link.
check_index() {
    local actual expected path text
    actual=$(index_listing)
    case $actual in
        *' -> /'*) fail "a sherlock-kit package tracks an absolute symlink: $actual" ;;
    esac
    expected=$(expected_listing)
    if [[ "$actual" != "$expected" ]]; then
        printf '%s\n' "$expected" >"$TEST_TMP/expected-index"
        printf '%s\n' "$actual" >"$TEST_TMP/actual-index"
        diff -u "$TEST_TMP/expected-index" "$TEST_TMP/actual-index" >&2 || true
        fail 'the tracked sherlock-kit packages differ from the delivery layout'
    fi
    while read -r path text; do
        [[ -L "$REPO_ROOT/$path" ]] || fail "$path is not a symlink in the checkout"
        [[ "$(readlink "$REPO_ROOT/$path")" == "$text" ]] ||
            fail "$path links to $(readlink "$REPO_ROOT/$path"), expected $text"
    done <<<"$LINKS"
}

# Only lab-ubuntu, wsl-ubuntu and sherlock carry a host package; the others
# get nothing, and Windows never stows the common package.
check_hosts() {
    local package host patterns allowlist
    for package in "$REPO_ROOT"/*/sherlock-kit; do
        [[ -e "$package" || -L "$package" ]] || continue
        host=${package%/sherlock-kit}
        host=${host##*/}
        case " common $HOSTS " in
            *" $host "*) ;;
            *) fail "$host/sherlock-kit exists; only $HOSTS get the sherlock-kit rules, skills and shk" ;;
        esac
    done
    for host in $HOSTS; do
        [[ -d "$REPO_ROOT/$host/sherlock-kit" ]] || fail "missing host package $host/sherlock-kit"
    done
    [[ -f "$REPO_ROOT/common/sherlock-kit/.stow-local-ignore" ]] || fail 'missing common/sherlock-kit/.stow-local-ignore'
    patterns=$(grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$REPO_ROOT/common/sherlock-kit/.stow-local-ignore") ||
        patterns=
    [[ "$patterns" == '^/sherlock-kit$'$'\n''^/sherlock-kit/' ]] ||
        fail "common/sherlock-kit/.stow-local-ignore must hold only the anchored ^/sherlock-kit\$ and ^/sherlock-kit/: $patterns"
    allowlist=$(grep -E '^\$CommonPackages = @\(' "$REPO_ROOT/stow-all.ps1") ||
        fail 'stow-all.ps1 has no $CommonPackages allowlist'
    case $allowlist in
        *sherlock-kit*) fail "stow-all.ps1 must not stow the POSIX-only sherlock-kit package: $allowlist" ;;
    esac
}

# check_no_dev_checkout ROOT: no tracked file of ROOT names the dev checkout.
# sherlock-kit's own docs do, so git grep must not follow submodule.recurse.
check_no_dev_checkout() {
    local matches rc=0
    matches=$(git -C "$1" grep --no-recurse-submodules -n -F -e "$DEV_CHECKOUT") || rc=$?
    case $rc in
        0) fail "tracked files name the sherlock-kit dev checkout: $matches" ;;
        1) ;;
        *) fail "git grep failed ($rc)" ;;
    esac
}

# The bump Action refuses a bump that breaks delivery before it commits, and
# the Sherlock profile runs shk's Slurm programs locally.
check_automation() {
    local workflow=$REPO_ROOT/.github/workflows/update-sherlock-kit-submodule.yml stage guard commit
    [[ -f "$workflow" ]] || fail "missing ${workflow#"$REPO_ROOT"/}"
    grep -Fq 'cron: "30 4 * * *"' "$workflow" || fail 'the sherlock-kit bump must run at 04:30 UTC'
    grep -Fq "git submodule update --remote --merge $SUBMODULE" "$workflow" ||
        fail "the Action must bump $SUBMODULE"
    guard=$(grep -m 1 -n -F 'bash tests/sherlock-kit-delivery.sh --real' "$workflow" | cut -d: -f1) || guard=
    commit=$(grep -m 1 -n -F 'git commit' "$workflow" | cut -d: -f1) || commit=
    stage=$(grep -m 1 -n -F "git add $SUBMODULE" "$workflow" | cut -d: -f1) || stage=
    [[ -n "$guard" && -n "$commit" && "$guard" -lt "$commit" ]] ||
        fail 'the Action must run tests/sherlock-kit-delivery.sh --real before it commits'
    [[ -n "$stage" && "$stage" -lt "$guard" ]] ||
        fail 'the Action must stage its bump before --real checks the recorded gitlink'
    grep -Fxq 'export SHK_EXECUTOR=local' "$REPO_ROOT/sherlock/sh/.config/sh/.profile" ||
        fail 'the Sherlock profile must export SHK_EXECUTOR=local'
}

# fake_contract DIR: the contract files a sherlock-kit checkout provides.
fake_contract() {
    mkdir -p "$1/$DATA/rules" "$1/$DATA/skills/sherlock-kit" "$1/bin"
    printf '%s\n' '## Sherlock from this workstation' 'fixture workstation rules' >"$1/$DATA/rules/workstation.md"
    printf '%s\n' '## Sherlock: agent running on Sherlock' 'fixture cluster rules' >"$1/$DATA/rules/cluster.md"
    printf '%s\n' '---' 'name: sherlock-kit' 'description: fixture skill' '---' 'fixture skill body' \
        >"$1/$DATA/skills/sherlock-kit/SKILL.md"
    printf '%s\n' '#!/bin/sh' 'echo fixture-shk' >"$1/bin/shk"
    chmod 755 "$1/bin/shk"
}

# check_real ROOT: the submodule of ROOT is checked out at the gitlink the
# index records (what a commit would carry and the hosts would check out),
# that commit has C1-C4, and every delivered link resolves. An uninitialized
# submodule or an unstaged bump fails instead of passing; the bump Action
# stages its bump first.
check_real() {
    local root=$1 checkout=$1/$SUBMODULE path text revision recorded
    [[ -e "$checkout/.git" ]] ||
        fail "sherlock-kit submodule not initialized at $SUBMODULE; run git submodule update --init --recursive"
    revision=$(git -C "$checkout" rev-parse HEAD)
    recorded=$(git -C "$root" ls-files -s -- "$SUBMODULE" | cut -d' ' -f2)
    [[ "$revision" == "$recorded" ]] ||
        fail "sherlock-kit is checked out at $revision, which is not the recorded gitlink $recorded; stage the bump (git add $SUBMODULE) or check out the recorded commit (git submodule update)"
    for path in $CONTRACT; do
        [[ -f "$checkout/$path" ]] ||
            fail "sherlock-kit $revision lacks $path (contract C1-C4); the delivered links would dangle"
    done
    [[ -x "$checkout/bin/shk" ]] || fail "sherlock-kit $revision: bin/shk is not executable"
    while read -r path text; do
        [[ -e "$root/$path" ]] || fail "$path -> $text dangles with sherlock-kit $revision"
    done <<<"$LINKS"
    printf 'sherlock-kit-delivery: real submodule %s resolves every delivered link\n' "$revision"
}

TEST_TMP="$(mktemp -d "${TMPDIR:-/tmp}/dotfiles-sherlock-kit-delivery.XXXXXX")"
# macOS TMPDIR ends in '/', and /var may itself be a symlink.
TEST_TMP="$(cd -- "$TEST_TMP" && pwd -P)"
trap 'rm -rf "$TEST_TMP"' EXIT HUP INT TERM

check_gitmodules
check_index
check_hosts
check_no_dev_checkout "$REPO_ROOT"
check_automation

if [[ "$real" == 1 ]]; then
    check_real "$REPO_ROOT"
    echo 'sherlock-kit-delivery=PASS'
    exit 0
fi

# real_fixture ROOT: a superproject like a host checkout after git submodule
# update --init, with the host links and an active submodule. Its first
# commit (BARE_COMMIT) has only docs that name the dev checkout, as
# sherlock-kit's own CONTRIBUTING.md does; the second, which the gitlink
# records, adds the contract.
real_fixture() {
    local root=$1 checkout=$1/$SUBMODULE host
    fixture_git init -q "$root"
    for host in $HOSTS; do
        mkdir "$root/$host"
        cp -RP "$REPO_ROOT/$host/sherlock-kit" "$root/$host/"
    done
    cp "$REPO_ROOT/.gitmodules" "$root/"
    mkdir -p "$checkout"
    fixture_git init -q "$checkout"
    printf 'Develop in ~/%s.\n' "$DEV_CHECKOUT" >"$checkout/CONTRIBUTING.md"
    fixture_git -C "$checkout" add CONTRIBUTING.md
    fixture_git -C "$checkout" commit -q -m docs
    BARE_COMMIT=$(fixture_git -C "$checkout" rev-parse HEAD)
    fake_contract "$checkout"
    fixture_git -C "$checkout" add src bin
    fixture_git -C "$checkout" commit -q -m contract
    fixture_git -C "$root" add .gitmodules
    fixture_git -C "$root" update-index --add --cacheinfo "160000,$(fixture_git -C "$checkout" rev-parse HEAD),$SUBMODULE"
    fixture_git -C "$root" submodule --quiet init -- "$SUBMODULE"
}

# expect_real_failure CASE ROOT TEXT: --real refuses ROOT, saying TEXT.
expect_real_failure() {
    if in_fixture_env check_real "$2" >"$TEST_TMP/real-$1.out" 2>&1; then
        cat "$TEST_TMP/real-$1.out" >&2
        fail "--real accepted the $1 fixture"
    fi
    expect_grep "$3" "$TEST_TMP/real-$1.out"
}

REAL_ROOT=$TEST_TMP/real/dotfiles
real_fixture "$REAL_ROOT"
# With submodule.recurse=true git grep also searches an active submodule,
# whose own docs may name the dev checkout.
fixture_git -C "$REAL_ROOT" config submodule.recurse true
in_fixture_env check_no_dev_checkout "$REAL_ROOT"
in_fixture_env check_real "$REAL_ROOT" >"$TEST_TMP/real-pass.out"
expect_grep 'resolves every delivered link' "$TEST_TMP/real-pass.out"
# A checkout that the gitlink does not record, such as an unstaged bump,
# says nothing about what the hosts check out.
fixture_git -C "$REAL_ROOT" update-index --cacheinfo "160000,$BARE_COMMIT,$SUBMODULE"
expect_real_failure unstaged "$REAL_ROOT" "is not the recorded gitlink $BARE_COMMIT"
# The recorded commit lacks the contract: every delivered link would dangle.
fixture_git -C "$REAL_ROOT/$SUBMODULE" checkout -q "$BARE_COMMIT"
expect_real_failure bare "$REAL_ROOT" "sherlock-kit $BARE_COMMIT lacks $DATA/rules/workstation.md"
# An uninitialized submodule fails instead of passing.
rm -rf "${REAL_ROOT:?}/$SUBMODULE"
mkdir "$REAL_ROOT/$SUBMODULE"
expect_real_failure uninitialized "$REAL_ROOT" "sherlock-kit submodule not initialized at $SUBMODULE"

if ! command -v stow >/dev/null 2>&1; then
    skip 'real GNU Stow for the sherlock-kit fixture stow (install stow to enable)'
    echo 'sherlock-kit-delivery=PASS'
    exit 0
fi
SYNC_PYTHON="${DOTFILES_SYNC_PYTHON:-$REPO_ROOT/.venv-sync/bin/python}"
if [[ ! -x "$SYNC_PYTHON" ]]; then
    fail 'AI-sync runtime missing; run ./setup-sync.sh explicitly.'
fi

# make_home HOME [initialized]: a temporary home holding a checkout subset at
# ~/dotfiles, as on the hosts, with an empty or a fake submodule.
make_home() {
    local home=$1 host
    local checkout=$home/dotfiles
    mkdir -p "$checkout/common/sherlock-kit/sherlock-kit" "$checkout/lib" "$home/.oh-my-zsh"
    # Tool packages carry completions and require the prerequisite OMZ clone.
    printf '%s\n' '# fixture oh-my-zsh entrypoint' >"$home/.oh-my-zsh/oh-my-zsh.sh"
    cp "$REPO_ROOT/stow-all.sh" "$REPO_ROOT/.stowrc" "$checkout/"
    cp "$REPO_ROOT/lib/config_sync.py" "$REPO_ROOT/lib/sync-runtime.sh" "$REPO_ROOT/lib/terminal.sh" "$checkout/lib/"
    cp -RP "$REPO_ROOT/common/codex" "$REPO_ROOT/common/claude" "$checkout/common/"
    # The coding-agent-kit checkout comes along as a plain tree, without its gitfile.
    rm -f "$checkout/common/codex/coding-agent-kit/.git"
    cp -P "$REPO_ROOT/common/sherlock-kit/.stow-local-ignore" "$checkout/common/sherlock-kit/"
    for host in $HOSTS; do
        mkdir "$checkout/$host"
        cp -RP "$REPO_ROOT/$host/sherlock-kit" "$checkout/$host/"
    done
    if [[ "${2:-}" == initialized ]]; then
        fake_contract "$checkout/$SUBMODULE"
    fi
}

# stow_home CASE HOME [HOST]: the real stow-all.sh, hermetic and expected to
# succeed; its output is kept as CASE.stdout and CASE.stderr.
stow_home() {
    local name=$1 home=$2
    shift 2
    if ! run_stow_all "$name" "$home" "$@"; then
        cat "$TEST_TMP/$name.stdout" "$TEST_TMP/$name.stderr" >&2
        fail "stow-all.sh ${1:-(common-only)} failed in case $name"
    fi
}

run_stow_all() {
    local name=$1 home=$2
    shift 2
    (
        unset_git_env
        export HOME="$home" GIT_CEILING_DIRECTORIES="$TEST_TMP" DOTFILES_SYNC_PYTHON="$SYNC_PYTHON" LC_ALL=C
        exec bash "$home/dotfiles/stow-all.sh" "$@"
    ) >"$TEST_TMP/$name.stdout" 2>"$TEST_TMP/$name.stderr"
}

# assert_delivered HOME RULES-LINE: the links of a host package, resolved.
assert_delivered() {
    local home=$1 skill
    [[ -L "$home/.claude/rules/sherlock-kit.md" ]] || fail "$home/.claude/rules/sherlock-kit.md is not a link"
    expect_line "$2" "$home/.claude/rules/sherlock-kit.md"
    for skill in .claude/skills/sherlock-kit .agents/skills/sherlock-kit; do
        [[ -L "$home/$skill" ]] || fail "$home/$skill is not a link (Stow folded or copied it)"
        [[ -d "$home/${skill%/*}" && ! -L "$home/${skill%/*}" ]] || fail "$home/${skill%/*} is not a real directory"
        [[ -f "$home/$skill/SKILL.md" ]] || fail "$home/$skill/SKILL.md does not resolve"
        expect_line 'name: sherlock-kit' "$home/$skill/SKILL.md"
    done
    [[ -L "$home/.local/bin/shk" ]] || fail "$home/.local/bin/shk is not a link"
    [[ "$("$home/.local/bin/shk")" == fixture-shk ]] || fail "$home/.local/bin/shk does not run the submodule's bin/shk"
    [[ ! -e "$home/sherlock-kit" && ! -L "$home/sherlock-kit" ]] || fail 'Stow linked the submodule checkout itself'
    [[ ! -e "$home/.stow-local-ignore" && ! -L "$home/.stow-local-ignore" ]] || fail 'Stow linked .stow-local-ignore'
}

# assert_override HOME RULES-LINE OTHER-RULES-LINE: the generated Codex
# instructions are the marker, the portable AGENTS.md and this host's rules.
assert_override() {
    local override=$1/.codex/AGENTS.override.md
    [[ -f "$override" && ! -L "$override" ]] || fail "no generated $override"
    [[ "$(head -n 1 "$override")" == "$MARKER" ]] || fail "$override does not start with the marker"
    expect_line "$(head -n 1 "$REPO_ROOT/common/codex/.codex/AGENTS.md")" "$override"
    expect_line "$2" "$override"
    refute_grep "$3" "$override"
}

# lab-ubuntu over a 0.3 home: a real ~/.claude/rules with a foreign rule,
# and the retired dangling ~/.local/bin/shk -> ../../dotfiles/common/codex/...
HOME_LAB=$TEST_TMP/lab/home
make_home "$HOME_LAB" initialized
mkdir -p "$HOME_LAB/.claude/rules" "$HOME_LAB/.local/bin"
printf '%s\n' 'a foreign rule' >"$HOME_LAB/.claude/rules/foreign.md"
ln -s ../../dotfiles/common/codex/.local/bin/shk "$HOME_LAB/.local/bin/shk"
stow_home lab "$HOME_LAB" lab-ubuntu
expect_grep '[dotfiles] [ok] Stow completed (lab-ubuntu)' "$TEST_TMP/lab.stdout"
expect_line "[dotfiles] [info] Removed retired link $HOME_LAB/.local/bin/shk (its source common/codex/.local/bin/shk was deleted)" \
    "$TEST_TMP/lab.stdout"
assert_delivered "$HOME_LAB" 'fixture workstation rules'
refute_grep 'fixture cluster rules' "$HOME_LAB/.claude/rules/sherlock-kit.md"
[[ "$(readlink "$HOME_LAB/.local/bin/shk")" == ../../dotfiles/lab-ubuntu/sherlock-kit/.local/bin/shk ]] ||
    fail 'the retired ~/.local/bin/shk was not replaced by the host link'
[[ -d "$HOME_LAB/.claude/rules" && ! -L "$HOME_LAB/.claude/rules" ]] || fail "$HOME_LAB/.claude/rules is no longer a real directory"
expect_line 'a foreign rule' "$HOME_LAB/.claude/rules/foreign.md"
assert_override "$HOME_LAB" 'fixture workstation rules' 'fixture cluster rules'
refute_grep 'sherlock-kit submodule not initialized' "$TEST_TMP/lab.stderr"
# Restow is idempotent.
stow_home lab-again "$HOME_LAB" lab-ubuntu
assert_delivered "$HOME_LAB" 'fixture workstation rules'
refute_grep 'Removed retired link' "$TEST_TMP/lab-again.stdout"
# The awesome-skills updater syncs additively (rsync -a without --delete), so
# the linked skill survives a sync that brings other skills.
if command -v rsync >/dev/null 2>&1; then
    mkdir -p "$TEST_TMP/awesome/other-skill"
    printf '%s\n' 'other' >"$TEST_TMP/awesome/other-skill/SKILL.md"
    rsync -a "$TEST_TMP/awesome/" "$HOME_LAB/.claude/skills/"
    [[ -L "$HOME_LAB/.claude/skills/sherlock-kit" && -f "$HOME_LAB/.claude/skills/other-skill/SKILL.md" ]] ||
        fail 'an additive skills sync replaced the sherlock-kit skill link'
else
    skip 'rsync for the additive skills-sync check'
fi

# The Sherlock host gets the on-cluster rules, into a home without ~/.claude.
HOME_SH=$TEST_TMP/sherlock/home
make_home "$HOME_SH" initialized
stow_home sherlock "$HOME_SH" sherlock
expect_grep '[dotfiles] [ok] Stow completed (sherlock)' "$TEST_TMP/sherlock.stdout"
assert_delivered "$HOME_SH" 'fixture cluster rules'
refute_grep 'fixture workstation rules' "$HOME_SH/.claude/rules/sherlock-kit.md"
assert_override "$HOME_SH" 'fixture cluster rules' 'fixture workstation rules'

# An uninitialized (empty) submodule, as after a plain local merge: only the
# Codex instructions are skipped, with the warning; the rest of the stow
# completes, and the links resolve once the submodule is checked out.
HOME_EMPTY=$TEST_TMP/uninitialized/home
make_home "$HOME_EMPTY"
stow_home uninitialized "$HOME_EMPTY" lab-ubuntu
